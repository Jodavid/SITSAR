test_that("SARImage basics", {
  img <- SARImage$new(SanFrancisco150, looks = 4)
  expect_equal(img$type, "polsar")
  expect_equal(img$m, 3L)
  expect_equal(c(img$nrow, img$ncol), c(150L, 150L))
  expect_equal(img$channels, c("HH", "HV", "VV"))
  P <- img$pixel(2, 3)
  expect_equal(dim(P), c(3L, 3L))
  expect_equal(Re(P[1, 1]), Re(SanFrancisco150[2, 3, 1]))
  cr <- img$crop(1:10, 5:20)
  expect_equal(c(cr$nrow, cr$ncol), c(10L, 16L))
  expect_equal(nrow(img$window(1, 1, 5)), 9L)
  expect_equal(nrow(img$window(50, 50, 5)), 25L)
  pa <- img$pauli()
  expect_equal(dim(pa), c(150L, 150L, 3L))
  expect_true(all(pa >= 0 & pa <= 1))
  tb <- tibble::as_tibble(cr)
  expect_equal(nrow(tb), 160L)
  expect_true(all(c("row", "col", "HH", "HH_HV_re", "HV_VV_im") %in% names(tb)))
  expect_output(print(img), "PolSAR")
  ii <- SARImage$new(Re(SanFrancisco150[, , 1:3]))
  expect_equal(ii$type, "intensity")
  expect_error(SARImage$new(1:3), "matrix")
})

test_that("local features match direct computations", {
  img <- SARImage$new(SanFrancisco150)$crop(1:20, 1:25)
  f <- sar_features(img, window = 3)
  expect_equal(nrow(f), 500L)
  r <- which(f$row == 7 & f$col == 9)
  w <- img$window(7, 9, 3)
  I <- Re(w[, 1:3])
  expect_equal(f$mean_HV[r], mean(I[, 2]))
  expect_equal(f$cov_HH_VV[r], cov(I[, 1], I[, 3]))
  expect_equal(complex(real = f$c13_re[r], imaginary = f$c13_im[r]), mean(w[, 5]))
  # border windows are truncated
  r1 <- which(f$row == 1 & f$col == 1)
  expect_equal(f$mean_HH[r1], mean(Re(img$window(1, 1, 3)[, 1])))
  expect_error(sar_features(img, window = 4), "odd")
  fi <- sar_features(SARImage$new(Re(SanFrancisco150[1:5, 1:5, 1:3])), window = 3)
  expect_false(any(grepl("^c11$", names(fi))))
})

test_that("plots run without error", {
  img <- SARImage$new(SanFrancisco150)$crop(1:30, 1:30)
  pdf(NULL)
  on.exit(dev.off())
  expect_silent(img$plot())
  expect_silent(img$plot("intensity", channel = "HV"))
  expect_silent(plot_map(SanFrancisco150_gt))
  expect_silent(plot_map(matrix(runif(100), 10)))
})
