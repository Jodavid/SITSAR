test_that("EM segmentation recovers a simulated partition", {
  set.seed(40)
  truth <- matrix(1L, 40, 40); truth[, 21:40] <- 2L
  x <- matrix(rgammasar(1600, ifelse(truth == 1, 1, 6), 4), 40)
  H <- entropy_map(x, "gamma", window = 5, L = 4)
  seg <- EntropySegmenter$new(k = 2)$fit(H)
  expect_equal(dim(seg$label_map()), c(40L, 40L))
  ks <- kappa_statistics(truth, seg$label_map(), match = TRUE)
  expect_gt(ks$kappa, 0.85)
  expect_equal(length(seg$weights), 2L)
  expect_true(seg$means[1, 1] < seg$means[2, 1])
  pr <- seg$predict(H)
  expect_equal(pr, seg$label_map())
  seg2 <- EntropySegmenter$new(k = 2, method = "sem", max_iter = 30)$fit(H)
  expect_gt(kappa_statistics(truth, seg2$label_map(), match = TRUE)$kappa, 0.85)
  expect_output(print(seg), "EntropySegmenter")
})

test_that("segmentation of the San Francisco image", {
  set.seed(41)
  seg <- segment_sar(SanFrancisco150, k = 3, model = "wishart", window = 7, L = 4)
  ks <- kappa_statistics(SanFrancisco150_gt, seg$label_map(), match = TRUE)
  expect_gt(ks$overall_accuracy, 0.6)
  H <- entropy_map(SanFrancisco150, "gamma", window = 7, L = 4)
  seg3 <- EntropySegmenter$new(k = 3)$fit(H)
  expect_equal(seg3$dim, c(150L, 150L))
  expect_equal(ncol(seg3$means), 3L)
  seg4 <- EntropySegmenter$new(k = 2)$fit(cbind(a = rnorm(50), b = rnorm(50)), is_map = FALSE)
  expect_null(seg4$dim)
  expect_error(seg4$label_map(), "not fitted to a map")
})
