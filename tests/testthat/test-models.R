test_that("EM for compound Wishart models", {
  set.seed(24)
  S <- polsar_example_sigma("forest")
  x <- rctpcw(800, lambda = 2, Sigma = S, L = 4)
  m <- CompoundWishart$new("poisson")$fit(x, L = 4)
  expect_true(m$converged)
  expect_equal(m$params$lambda, 2, tolerance = 0.2)
  expect_lt(max(Mod(m$params$Sigma - S)) / max(Mod(S)), 0.2)
  y <- rcgcw(800, p = 0.4, Sigma = S, L = 4)
  m2 <- CompoundWishart$new("geometric")$fit(y, L = 4)
  expect_equal(m2$params$p, 0.4, tolerance = 0.2)
  expect_true(is.finite(m2$entropy(nsim = 200)))
  expect_error(m2$entropy_variance())
})

