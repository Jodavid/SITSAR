test_that("G0I maximum likelihood estimation", {
  set.seed(20)
  z <- rg0i(4000, -3, 2, 4)
  m <- G0I$new()$fit(z, L = 4)
  expect_s3_class(m, "R6")
  expect_equal(m$params$alpha, -3, tolerance = 0.15)
  expect_equal(m$params$gamma, 2, tolerance = 0.15)
  expect_identical(m$fixed, "L")
  m2 <- G0I$new()$fit(z)
  expect_equal(m2$params$L, 4, tolerance = 0.15)
  expect_true(m2$loglik >= m$loglik - 1e-6)
  expect_gt(m$entropy_variance(), 0)
  td <- generics::tidy(m)
  expect_s3_class(td, "tbl_df")
  expect_equal(td$term, c("alpha", "gamma", "L"))
  gl <- generics::glance(m2)
  expect_equal(gl$n, 4000)
  expect_equal(attr(logLik(m2), "df"), 3)
  expect_equal(g0iestimation(c(-1, 1, 4), z, L_fixed = TRUE)[["alpha"]], m$params$alpha,
               tolerance = 1e-4)
})

test_that("asymptotic entropy variance matches simulation", {
  set.seed(21)
  h <- replicate(150, G0I$new()$fit(rg0i(300, -3, 2, 4), L = 4)$entropy())
  v <- G0I$new()$fit(rg0i(5000, -3, 2, 4), L = 4)$entropy_variance(n = 300)
  expect_equal(sd(h), sqrt(v), tolerance = 0.2)
  S <- polsar_example_sigma("forest")
  hw <- replicate(150, WishartSAR$new()$fit(rwishart_sar(100, S, 4))$entropy())
  vw <- WishartSAR$new()$fit(rwishart_sar(100, S, 4))$entropy_variance()
  expect_equal(sd(hw), sqrt(vw), tolerance = 0.25)
})

test_that("Gamma, generalized Gamma and Wishart estimation", {
  set.seed(22)
  g <- GammaSAR$new()$fit(rgammasar(5000, 2, 4))
  expect_equal(g$params$mu, 2, tolerance = 0.03)
  expect_equal(g$params$L, 4, tolerance = 0.05)
  gg <- GGammaSAR$new()$fit(rggamma(5000, 2, 3, 1))
  expect_true(is.finite(gg$loglik))
  expect_gte(gg$loglik, GGammaSAR$new(2, 3, 1)$log_likelihood(rggamma(1, 2, 3, 1)) - Inf)
  ggf <- GGammaSAR$new()$fit(rggamma(5000, 2, 3, 1), phi = 3)
  expect_equal(ggf$params$alpha, 2, tolerance = 0.05)
  S <- polsar_example_sigma("urban")
  w <- WishartSAR$new()$fit(rwishart_sar(3000, S, 6))
  expect_equal(w$params$L, 6, tolerance = 0.05)
  expect_lt(max(Mod(w$params$Sigma - S)) / max(Mod(S)), 0.05)
})

